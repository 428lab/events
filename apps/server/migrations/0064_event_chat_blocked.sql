-- チャットの発言者単位の締め出し (#283)。
--
-- 運営のコンテンツ対処 (#278) は1件ずつなので、1人が大量に投稿すると手数が足りない。
-- チャットの表示は「発言者の公開鍵の許可リスト」(event_chat_pubkey) で絞っているので、
-- 鍵を1つ落とせば、その人のこれまでの発言がまとめて表示されなくなる。
--
-- 許可リストの行そのもの（event_chat_pubkey）は消さずに、**別テーブルで締め出しを持つ**。
-- 消してしまうと解除したときに元に戻せず、誤操作を取り返せなくなる。
--
-- 効く範囲は **このアプリの中だけ**。チャット本文はサーバーを通らず、ブラウザが
-- 直接リレーとやり取りしていて、表示の絞り込みもブラウザ側で掛かっている。
-- 締め出すと「このアプリの表示から消え、このアプリからは投稿できなくなる」であって、
-- リレーへの書き込みそのものを止めるものではない（外部のクライアントからは投稿できる。
-- ただしその発言はこのアプリの誰の画面にも出ない）。
--
-- 限界（承知のうえ）: 締め出された人が別の鍵で入り直すことも防げない。
-- これは「その場の荒らしを止める」ための道具であって、恒久的な追放ではない。
CREATE TABLE event_chat_blocked (
  event_id TEXT NOT NULL REFERENCES event(id) ON DELETE CASCADE,
  -- 締め出す発言者の公開鍵（event_chat_pubkey.pubkey と同じ値）。
  -- 許可リストに行が無い鍵でも先に登録できるようにするため FK は張らない
  pubkey TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  -- 操作した運営管理者の user id。監査ログ (#248) と同じ方針で user への FK は張らない
  -- （退会・統合でユーザー行が消えても記録を残す）
  created_by TEXT,
  PRIMARY KEY (event_id, pubkey)
);
