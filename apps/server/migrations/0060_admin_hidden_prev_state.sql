-- 運営が対処する **前** の非表示の状態を控える (#278 のレビュー反映)。
--
-- Q&A とチャットにはスタッフ用の非表示が元からある。0059 の作りでは、運営が対処すると
-- スタッフの非表示と見分けが付かなくなり（Q&A は q.hidden = 1 かつ admin_hidden_at IS NULL
-- でしかスタッフの非表示を判定できず、チャットは行の有無しか無い）、
-- 運営が復元したときに「スタッフが非表示にしていた」判断まで取り消してしまっていた。
--
-- ここに対処前の値を控えておき、復元はその状態に戻す（**運営の対処だけを解く**）。
-- 管理画面も、運営が対処したあとに「スタッフも非表示にしていた」を出せるようになる。
--
-- 値: 1 = 運営が対処する前からスタッフが非表示にしていた / 0 = していなかった /
--     NULL = 運営が対処していない（既存行はすべてこれ。移行時の UPDATE は不要）。
ALTER TABLE event_question ADD COLUMN admin_prev_hidden INTEGER;

-- チャットは event_chat_hidden の **行があること自体** が非表示なので、
-- 「運営が対処したときに行が既にあったか」がそのままスタッフの非表示にあたる。
-- 復元時は 1 なら行を残して目印だけ外し、0 なら行ごと消す。
ALTER TABLE event_chat_hidden ADD COLUMN admin_prev_hidden INTEGER;
