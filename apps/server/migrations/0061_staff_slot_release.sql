-- 参加者以外のロールは参加枠を消費しない (#277)。
--
-- これまでロール変更は role だけを書き換えていたため、抽選枠に応募中(applied)や
-- 先着枠のキャンセル待ち(waitlist)のままスタッフになれてしまった。その後に抽選を
-- 実行するとスタッフが落選(lost)になり、画面はロールを見て操作UIを出すのに
-- サーバーは参加確定を要求するので、削除や非表示の操作が無言で403になっていた。
--
-- ここでは既に同じ状態になっている行を整理する。参加者以外(staff/judge/observer)で
-- 参加状態が確定でない行を、枠を外して確定にする。取消済み(canceled)は参加履歴
-- として残す行なので触らない。
--
-- 確定済みで枠を持っている行はそのままにする。参加者数の見え方が変わるだけで
-- 「操作が403になる」問題は起きておらず、過去の集計を後から動かしたくないため。
UPDATE event_member
   SET slot_id = NULL, status = 'confirmed'
 WHERE role <> 'participant'
   AND status NOT IN ('confirmed', 'canceled');
