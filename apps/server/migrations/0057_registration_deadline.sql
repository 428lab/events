-- イベントの募集締切日時 (#269)。
--
-- これまで参加登録を止める手段が無く、開始直前どころか開催中でも登録できた。
-- 会場への人数報告・資料や飲食の手配があるため、主催者が「ここで締める」時刻を
-- 決められるようにする。
--
-- NULL = 締切なし。**既存の全イベントは NULL になるので振る舞いが変わらない**
-- （従来どおりイベント終了 ends_at まで受け付ける）。DEFAULT は付けない：
-- 「未設定」を NULL 一種類で表したいので、0 と NULL の2系統を作らない。
--
-- 効くのは「新規の参加登録」だけ。締切後も次はすべて従来どおり動く:
--   - 既存参加者のキャンセル（DELETE /events/:id/join）
--   - キャンセルによるキャンセル待ちの繰り上げ
--   - スタッフのロール変更・当選操作・出席チェック・QR受付
-- 当日運営でスタッフが手を入れられなくなると詰むため。
--
-- インデックスは張らない。この列は「そのイベントを開いたとき」にしか読まれず
-- （参加登録時の1件判定と詳細表示）、一覧の絞り込み・並べ替えには使わないため。
-- 締切間近のリマインダー配信（#39 とは別枠）を作るときに、走査が必要なら
-- そこで scheduling/status との複合インデックスを検討すること。
ALTER TABLE event ADD COLUMN registration_deadline INTEGER;
