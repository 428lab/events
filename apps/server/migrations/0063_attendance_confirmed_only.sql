-- 出席にできるのは参加確定の人だけ (#286)。
--
-- 参加者一覧からの手動の出席チェック (PATCH /events/:id/members/:userId/attendance)
-- には参加状態の検査が無く、抽選に落選した人・抽選申込中の人・キャンセル待ちの人を
-- 出席にできてしまっていた。受付のQR経由 (POST /events/:id/checkin) は元から参加確定
-- を求めていたので、手動経路をそちらに揃えた。ここでは既に付いてしまった記録を消す。
--
-- 対象は落選(lost)・抽選申込中(applied)・キャンセル待ち(waitlist)の行だけ。
-- 参加枠を得ていない人なので、出席として残す理由が無い。
--
-- 取消済み(canceled)は触らない。「出席したあとで取り消した」という順番は実際に
-- 起こりうるし、集計は取消済みを既に除いているので残しても数字は動かない。
-- 参加履歴として残す行を消さない方針 (0061 と同じ) にも揃えている。
--
-- 集計への影響はほぼ無い。参加実績・KPI・参加者数・コミュニティKPI はいずれも
-- status = 'confirmed' で絞ってから attended を見ているので、ここで消す行は元から
-- 数えられていない。変わるのは次の2つ:
--   - イベント写真の閲覧可否 (routes/eventPhotos.ts)。出席チェックモードでは
--     attended = 1 の参加者に見せていたため、落選者が見られる状態が残っていた
--   - 全体KPI の「出席未記録イベント数」の判定 (repositories/kpi.ts)。
--     落選者の記録1件で「記録あり」と見なされていた分が正しくなる
UPDATE event_member
   SET attended = 0, attended_at = NULL
 WHERE attended = 1
   AND status IN ('lost', 'applied', 'waitlist');
